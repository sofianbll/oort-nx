#!/usr/bin/env python3
"""Generate the Android launcher's Kotlin tokens from design/oort.tokens.json.

It reads the file the Mac build reads and reuses its parser, its alias rules and its contrast check
(scripts/generate_oort_tokens.py), so a token cannot mean one thing on the Mac and another on Android.
Dimensions stay in Selene canvas units (1920x1080); the theme decides how a unit becomes dp or sp.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_oort_tokens import SOURCE, tokens, unique, verify_contrast  # noqa: E402
import json  # noqa: E402

OUTPUT = Path("android/app/src/main/kotlin/io/github/sofianbll/oortnx/ui/OortTokens.kt")
COLORS = Path("android/app/src/main/res/values/oort_colors.xml")
PACKAGE = "io.github.sofianbll.oortnx.ui"
GROUPS = {"color": "Palette", "status": "Status", "text": "Type", "space": "Space", "radius": "Radius",
          "effect": "Effect", "motion": "Motion", "distance": "Distance"}


def pascal(name):
    return "".join(part.title() for part in name.split("-"))


def kotlin(resolved):
    lines = ["// Generated by scripts/generate_oort_android_tokens.py from design/oort.tokens.json. Do not edit.",
             f"package {PACKAGE}", "", "import androidx.compose.ui.graphics.Color", "",
             "/** Selene canvas units are 1920x1080 px; durations are milliseconds. */",
             "object OortTokens {"]
    lines += ["    object Primitive {"]
    for key, (kind, value) in resolved.items():
        group, name = key.split(".")
        if group == "primitive":
            lines.append(f"        val {pascal(name)} = Color(0xFF{value:06X})")
    lines += ["    }", ""]
    for group, object_name in GROUPS.items():
        lines.append(f"    object {object_name} {{")
        for key, (kind, value) in resolved.items():
            prefix, name = key.split(".")
            if prefix != group:
                continue
            member = pascal(name)
            if kind == "color":
                lines.append(f"        val {member} = Color(0xFF{value:06X})")
            elif kind == "duration":
                lines.append(f"        const val {member}Ms: Int = {int(value)}")
            elif kind == "number":
                lines.append(f"        const val {member}: Float = {float(value)}f")
            else:
                lines.append(f"        const val {member}: Float = {float(value)}f")
        lines.append("    }")
        lines.append("")
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def colors_xml(resolved):
    # The window, the launcher icon and the system bars are drawn before Compose starts: they read resources.
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by scripts/generate_oort_android_tokens.py from design/oort.tokens.json. Do not edit. -->",
             "<resources>"]
    for key, (kind, value) in resolved.items():
        group, name = key.split(".")
        if group == "primitive":
            lines.append(f'    <color name="oort_{name.replace("-", "_")}">#FF{value:06X}</color>')
    return "\n".join(lines + ["</resources>"]) + "\n"


def generate(root, check):
    data = json.loads((root / SOURCE).read_text(), object_pairs_hook=unique)
    resolved = tokens(data)
    ratio = verify_contrast(resolved)
    for relative, expected in ((OUTPUT, kotlin(resolved)), (COLORS, colors_xml(resolved))):
        target = root / relative
        if check:
            if not target.exists() or target.read_bytes() != expected.encode():
                raise ValueError(f"Stale output: {relative}; run python3 scripts/generate_oort_android_tokens.py")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)
    print(f"{len(resolved)} Oort tokens for Android; minimum checked palette contrast {ratio:.2f}:1")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(ROOT, args.check)
    except (OSError, KeyError, AttributeError, ValueError, TypeError) as error:
        parser.exit(1, f"{error}\n")
