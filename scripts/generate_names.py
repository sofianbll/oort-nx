#!/usr/bin/env python3
"""Write every copy of architecture/names.json that cannot read it: the names block of Package.swift and of
scripts/build_app.sh, the modules of the LikeC4 model (architecture/names.c4) and the resource bundle's name in Swift.

generate_names.py            write the copies
generate_names.py --check    fail when a copy differs from architecture/names.json (rule R4)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import names  # noqa: E402

ROOT = names.ROOT
BEGIN, END = "BEGIN GENERATED NAMES (architecture/names.json, scripts/generate_names.py)", "END GENERATED NAMES"
HEADER = "Generated by scripts/generate_names.py from architecture/names.json. Do not edit."
MODEL = "architecture/names.c4"
SWIFT_FILE = "Settings/GeneratedNames.swift"   # inside the library module, beside AppLocalization.swift


def swift_block():
    lines = [f'let packageName = "{names.PACKAGE}"']
    for role, module in names.MODULES.items():
        lines.append(f'let {role} = (name: "{module["name"]}", path: "{module["path"]}")')
    for role, test in names.TESTS.items():
        lines.append(f'let {role}Tests = (name: "{test["name"]}", path: "{test["path"]}")')
    return lines


def shell_block():
    return [f'APP_PRODUCT="{names.APP}"', f'RESOURCE_BUNDLE="{names.RESOURCE_BUNDLE}"',
            f'CORE_MODULE="{names.CORE}"', f'LIBRARY_MODULE="{names.LIBRARY}"', f'NXNATIVE_MODULE="{names.NXNATIVE}"']


def model():
    parents = {}
    for role, module in names.MODULES.items():
        parents.setdefault(module["model"], []).append((role, module))
    out = [f"// {HEADER}", "// Each module of Package.swift, with its layer: a module imports only lower layers.", "model {"]
    for parent, modules in parents.items():
        out.append(f"  extend {parent} {{")
        for role, module in modules:
            element = "cModule" if module.get("language") == "c" else "swiftModule"
            out += [f'    {role}Module = {element} "{module["name"]}" {{',
                    "      metadata {", f'        layer "{module["layer"]}"', f'        folder "{module["path"]}"', "      }",
                    "    }"]
        out.append("  }")
    return "\n".join(out + ["}", ""])


def swift_constant():
    return "\n".join([f"// {HEADER}", "",
                      "/// The compiled resources of this module; SwiftPM names them after the package and the target.",
                      "enum GeneratedNames {", f'    static let resourceBundle = "{names.RESOURCE_BUNDLE}"', "}", ""])


def with_block(text, comment, lines, where):
    start, stop = f"{comment} {BEGIN}", f"{comment} {END}"
    if text.count(start) != 1 or text.count(stop) != 1 or text.index(start) > text.index(stop):
        raise SystemExit(f"{where}: expected one '{start}' ... '{stop}' block")
    head, rest = text.split(start, 1)
    _, tail = rest.split(stop, 1)
    return head + start + "\n" + "\n".join(lines) + "\n" + stop + tail


def outputs():
    package = (ROOT / "Package.swift").read_text(encoding="utf-8")
    build = (ROOT / "scripts/build_app.sh").read_text(encoding="utf-8")
    return {
        "Package.swift": with_block(package, "//", swift_block(), "Package.swift"),
        "scripts/build_app.sh": with_block(build, "#", shell_block(), "scripts/build_app.sh"),
        MODEL: model(),
        f"{names.path('library')}/{SWIFT_FILE}": swift_constant(),
    }


def main(argv):
    check = argv == ["--check"]
    if argv not in ([], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    stale = []
    for relative, text in outputs().items():
        path = ROOT / relative
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(relative)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {relative}")
    for relative in stale:
        print(f"{relative}: differs from architecture/names.json; run scripts/generate", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
