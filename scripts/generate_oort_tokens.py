#!/usr/bin/env python3
"""Generate Selene's Swift tokens, the same values in CSS, and the default entry of its palette catalog."""
import argparse
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("design/oort.tokens.json")
SWIFT = Path("core/OortLibrary/Selene/SeleneTokens.swift")
PALETTES = Path("design/Selene/palettes.json")
CSS = Path("design/oort-tokens.css")
# The weights the Swift views name; SwiftUI has no number for them.
WEIGHTS = {"regular": 400, "medium": 500, "semibold": 600}
PALETTE_ROLES = ("focus", "on-focus", "ink", "scrim", "glass", "glyph", "success", "light")
GROUPS = {
    "text": "Text", "space": "Space", "radius": "Radius", "status": "Color",
    "alpha": "Alpha", "art": "Art", "effect": "Effect", "motion": "Motion", "distance": "Distance", "color": "Palette",
}
NAME = re.compile(r"[a-z]+(?:-[a-z0-9]+)*")


def unique(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError(f"Duplicate key: {key}")
        result[key] = value
    return result


def tokens(data):
    # shortcut: two-level, same-type aliases and 8-bit opaque sRGB; use a DTCG tool for additional modes.
    raw = {}
    for group, members in data.items():
        if group not in (*GROUPS, "primitive"):
            raise ValueError(f"Unsupported group: {group}")
        for name, leaf in members.items():
            if name.startswith("$"):
                continue
            if not NAME.fullmatch(name) or set(leaf) - {"$type", "$value", "$description"}:
                raise ValueError(f"Unsupported token: {group}.{name}")
            raw[f"{group}.{name}"] = leaf.get("$type", members.get("$type")), leaf["$value"]

    def resolve(key, trail=()):
        if key in trail:
            raise ValueError(f"Alias cycle: {' -> '.join((*trail, key))}")
        kind, value = raw[key]
        if isinstance(value, str) and re.fullmatch(r"\{[^{}]+\}", value):
            target = value[1:-1]
            if raw[target][0] != kind:
                raise ValueError(f"Wrong alias type: {key} -> {target}")
            return resolve(target, (*trail, key))
        if kind == "color":
            rgb = value["components"]
            if (set(value) != {"colorSpace", "components", "hex"} or value["colorSpace"] != "srgb"
                    or len(rgb) != 3 or any(type(c) not in (int, float) or not 0 <= c <= 1 for c in rgb)):
                raise ValueError(f"Expected opaque sRGB: {key}")
            hex_value = "#" + "".join(f"{round(c * 255):02X}" for c in rgb)
            if hex_value != value["hex"].upper() or any(abs(c * 255 - round(c * 255)) > 1e-9 for c in rgb):
                raise ValueError(f"Expected matching 8-bit RGB and hex: {key}")
            return kind, int(hex_value[1:], 16)
        units = {"dimension": "px", "duration": "ms"}
        if kind in units:
            if set(value) != {"value", "unit"} or value["unit"] != units[kind]:
                raise ValueError(f"Wrong unit: {key}")
            value = value["value"]
        if (kind not in (*units, "number") or type(value) not in (int, float)
                or not math.isfinite(value) or value < 0):
            raise ValueError(f"Invalid token: {key}")
        return kind, value

    return {key: resolve(key) for key in raw}


# Minimum contrast of each foreground on its surface. Text is `ink`; screen probes hold rendered text to it.
CONTRAST = (("ink", "glass", 4.5), ("ink", "scrim", 4.5), ("on-focus", "focus", 4.5), ("focus", "glass", 3),
            ("glyph", "glass", 3))
TEXT_CONTRAST = CONTRAST[0][2]


def verify_contrast(resolved):
    def luminance(role):
        kind, color = resolved[f"color.{role}"]
        if kind != "color":
            raise ValueError(f"Expected color: {role}")
        srgb = [((color >> shift) & 255) / 255 for shift in (16, 8, 0)]
        linear = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in srgb]
        return sum(a * b for a, b in zip(linear, (0.2126, 0.7152, 0.0722)))

    ratios = []
    for fg, bg, threshold in CONTRAST:
        low, high = sorted((luminance(fg), luminance(bg)))
        ratio = (high + 0.05) / (low + 0.05)
        if ratio < threshold:
            raise ValueError(f"Contrast {fg} / {bg}: {ratio:.2f}:1 < {threshold:g}:1")
        ratios.append(ratio)
    return min(ratios)


def swift_name(name):
    if name == "status-ok":
        return "statusOK"  # Preserve the existing Swift API.
    head, *tail = name.split("-")
    return head + "".join(part.title() for part in tail)


def swift(resolved):
    lines = ["// Generated by scripts/generate_oort_tokens.py. Do not edit.",
             "import Foundation", "", "public enum SeleneTokens {"]
    for group, swift_group in GROUPS.items():
        lines.append(f"    public enum {swift_group}" + (": CGFloat {" if group == "text" else " {"))
        for key, (kind, value) in resolved.items():
            prefix, name = key.split(".")
            if group != prefix:
                continue
            member = swift_name(name)
            if group == "text":
                if kind != "dimension":
                    raise ValueError(f"Expected text dimension: {key}")
                lines.append(f"        case {member} = {value}")
                continue
            swift_type = {"dimension": "CGFloat", "duration": "Double", "number": "Double", "color": "UInt32"}[kind]
            literal = f"0x{value:06X}" if kind == "color" else str(value / 1000 if kind == "duration" else value)
            lines.append(f"        public static let {member}: {swift_type} = {literal}")
        lines += ["    }", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def css_values(resolved):
    """One CSS variable per token, in canvas units (--u) like `canvas.u()`; a blur given in points stays in points."""
    lines = []
    for key, (kind, value) in resolved.items():
        group, name = key.split(".")
        if group in ("primitive", "color", "distance"):
            continue
        if kind == "color":
            text = f"#{value:06X}"
        elif kind == "dimension":
            text = f"{value}px" if name.endswith("-points") else f"calc({value} * var(--u))"
        else:
            text = f"{value}ms" if kind == "duration" else str(value)
        lines.append(f"  --{group}-{name}: {text};")
    return lines + [f"  --weight-{name}: {value};" for name, value in WEIGHTS.items()]


def css(resolved):
    # A page without a canvas of its own reads one unit as a sixteenth of the reader's text size; :where lets it say otherwise.
    return "\n".join(["/* Generated by scripts/generate_oort_tokens.py. Do not edit. */", ":where(:root) { --u: calc(1rem / 16); }",
                      ":root {", *css_values(resolved), "}"]) + "\n"


def palettes(resolved, catalog):
    # Replace just Oort's entry; imported palette bytes and order are untouched.
    start = re.match(r"\[\s*", catalog).end()
    old, size = json.JSONDecoder().raw_decode(catalog[start:])
    if old["id"] != "oort":
        raise ValueError("Expected Oort first in the legacy palette catalog")
    palette = {"id": "oort", "name": "Oort", "mode": "dark"}
    for role in PALETTE_ROLES:
        palette[swift_name(role)] = resolved[f"color.{role}"][1]
    palette["moonlight"] = "cloud"
    palette["base"] = {"kind": "radial", "stops": [
        {"color": resolved[f"color.gradient-{stop}"][1],
         "location": float(resolved[f"color.position-{stop}"][1])} for stop in ("start", "end")
    ]}
    entry = json.dumps(palette, indent=2).replace("\n", "\n  ")
    return catalog[:start] + entry + catalog[start + size:]


def generate(root, check):
    resolved = tokens(json.loads((root / SOURCE).read_text(), object_pairs_hook=unique))
    ratio = verify_contrast(resolved)
    outputs = {SWIFT: swift(resolved), CSS: css(resolved), PALETTES: palettes(resolved, (root / PALETTES).read_text())}
    for relative, expected in outputs.items():
        file = root / relative
        if check:
            if not file.exists() or file.read_bytes() != expected.encode():
                raise ValueError(f"Stale output: {relative}; run python3 scripts/generate_oort_tokens.py")
        else:
            file.write_text(expected)
    print(f"{len(resolved)} Oort tokens; minimum checked palette contrast {ratio:.2f}:1")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(ROOT, args.check)
    except (OSError, KeyError, AttributeError, ValueError, TypeError) as error:
        parser.exit(1, f"{error}\n")
