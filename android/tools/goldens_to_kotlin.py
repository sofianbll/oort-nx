#!/usr/bin/env python3
"""Turns goldens.json (made by make_goldens.swift from the Mac's own code) into Goldens.kt, so the Kotlin tests
need no JSON library. Run it after make_goldens; both outputs are committed."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "app/src/test"
data = json.loads((ROOT / "resources/goldens.json").read_text())
cloud, sounds = data["cloud"], data["sounds"]

lines = ["// Generated by android/tools/goldens_to_kotlin.py from goldens.json. Do not edit.",
         "package io.github.sofianbll.oortnx.core", "",
         "/** What the Mac's own Swift code produced, for the Kotlin ports to match. */",
         "object Goldens {",
         f"    const val CLOUD_COUNT = {cloud['count']}",
         "    /** count, sum x, sum y, sum z of each kind (shell, rim, disc). */",
         "    val CLOUD_KINDS = listOf("]
for k in ("0", "1", "2"):
    v = cloud["kinds"][k]
    lines.append(f"        doubleArrayOf({float(v['count'])}, {float(v['sum'][0])}, {float(v['sum'][1])}, {float(v['sum'][2])}),")
lines += ["    )", "    /** index, x, y, z, kind, nx, ny, nz. */", "    val CLOUD_SAMPLES = listOf("]
for s in cloud["samples"]:
    lines.append("        doubleArrayOf(" + ", ".join(str(float(x)) for x in [s["index"], *s["point"]]) + "),")
lines += ["    )", "",
          "    class Sound(val pack: String, val event: String, val step: Int, val frames: Int, val rms: Double, val probes: List<Pair<Int, Int>>)",
          "    val SOUNDS = listOf("]
for s in sounds:
    probes = ", ".join(f"{p['index']} to {p['left']}" for p in s["probes"])
    lines.append(f'        Sound("{s["pack"]}", "{s["event"]}", {s["step"]}, {s["frames"]}, {s["rms"]}, listOf({probes})),')
lines += ["    )", "}"]
out = ROOT / "kotlin/io/github/sofianbll/oortnx/core/Goldens.kt"
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(ROOT.parents[1])}: {len(cloud['samples'])} cloud samples, {len(sounds)} sounds")
