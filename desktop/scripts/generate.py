#!/usr/bin/env python3
"""Write ui/gen: the CSS tokens and palettes, the icons' codepoints and the texts.

Sources, never edited here: design/oort.tokens.json (through scripts/generate_oort_tokens.py, with its checks),
Resources/Selene/palettes.json, MaterialIcon.swift, Localizable.xcstrings. Texts the Mac app does not have are in
strings.json. `--check` fails when a file is stale or a text is missing.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "scripts"))
import generate_oort_tokens as tokens  # noqa: E402

LANGUAGES = ("en", "fr")
ROLES = {"focus": "focus", "onFocus": "on-focus", "ink": "ink", "scrim": "scrim", "glass": "glass", "glyph": "glyph",
         "success": "success", "light": "light"}


def color(value):
    return f"#{value:06X}"


def luminance(value):
    srgb = [((value >> shift) & 255) / 255 for shift in (16, 8, 0)]
    r, g, b = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in srgb]
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    low, high = sorted((luminance(a), luminance(b)))
    return (high + 0.05) / (low + 0.05)


def mix(a, b, t):
    return sum(round(((a >> s) & 255) * (1 - t) + ((b >> s) & 255) * t) << s for s in (16, 8, 0))


def toward(start, end, good):
    """`start`, moved to `end` only as far as it takes."""
    return next(c for c in (mix(start, end, t / 50) for t in range(51)) if good(c))


def css():
    data = json.loads((ROOT / "design/oort.tokens.json").read_text(encoding="utf-8"), object_pairs_hook=tokens.unique)
    resolved = tokens.tokens(data)
    tokens.verify_contrast(resolved)
    out = ["/* Generated by desktop/scripts/generate.py. Do not edit. */", ":root {"]
    for key, (kind, value) in resolved.items():
        group, name = key.split(".")
        if group in ("primitive", "color", "distance"):
            continue
        prop = f"--{group}-{name}"
        if kind == "color":
            out.append(f"  {prop}: {color(value)};")
        elif kind == "dimension":
            # Canvas units on the 1920 x 1080 reference; a blur given in points stays in points.
            out.append(f"  {prop}: {value}px;" if name.endswith("-points") else f"  {prop}: calc({value} * var(--u));")
        elif kind == "duration":
            out.append(f"  {prop}: {value}ms;")
        else:
            out.append(f"  {prop}: {value};")
    out.append(f"  --sun: #F4CE8E;")
    out.append("}")
    for p in json.loads((ROOT / "Resources/Selene/palettes.json").read_text(encoding="utf-8")):
        body = [f"--{css_name}: {color(p.get(role, p['glyph']))}" for role, css_name in ROLES.items()]
        # DESIGN.md: focus and glyph at 3:1 on a panel, text at 4.5:1. A palette that falls short moves just enough.
        panel = mix(p["glass"], p["ink"], resolved["effect.surface-raised"][1])
        body += [f"--ring-color: {color(toward(p['focus'], p['ink'], lambda c: ratio(c, panel) >= 3))}",
                 f"--mark: {color(toward(p['glyph'], p['ink'], lambda c: ratio(c, panel) >= 3))}",
                 f"--key: {color(toward(p['focus'], 0 if luminance(p['onFocus']) > 0.2 else 0xFFFFFF, lambda c: ratio(c, p['onFocus']) >= 4.5 and ratio(mix(c, p['glyph'], resolved['effect.surface-line-strong'][1]), p['onFocus']) >= 4.5))}"]
        stops = ", ".join(f"{color(s['color'])} {s['location'] * 100:g}%" for s in p["base"]["stops"])
        shape = "radial-gradient(ellipse 120% 120% at 50% 20%" if p["base"]["kind"] == "radial" else "linear-gradient(to bottom"
        body += [f"--base: {shape}, {stops})", f"color-scheme: {p['mode']}", f"--mode-{p['mode']}: 1"]
        selector = f'[data-palette="{p["id"]}"]'
        out.append((":root, " if p["id"] == "oort" else "") + selector + " { " + "; ".join(body) + "; }")
    return "\n".join(out) + "\n"


def literals(path):
    return re.findall(r'"((?:[^"\\\n]|\\.)*)"', path.read_text(encoding="utf-8"))


def used():
    """Every text the page or the core can show, by key."""
    keys = []
    for file in sorted((HERE / "ui").glob("*.js")):
        for quote, text in re.findall(r"\bt\(\s*(['\"])((?:(?!\1)[^\\]|\\.)+)\1", file.read_text(encoding="utf-8")):
            keys.append(text.replace("\\'", "'"))
    core = ROOT / "Sources/NXLibraryCore"
    for path in ("Settings/SettingsCatalog.swift", "Settings/SettingsSection.swift", "Library/LibraryFilter.swift"):
        keys += literals(core / path)
    keys += literals(ROOT / "Sources/OortCompanion/SettingRows.swift")
    keys += [f"Settings navigation: {c}" for c in ("general", "appearance", "sound", "controllers", "account", "home", "library", "integrations", "about")]
    keys += ["Settings navigation: Games", "Settings navigation: Profile"]
    return list(dict.fromkeys(keys))


def strings():
    catalog = json.loads((ROOT / "Sources/NXLibraryCore/Resources/Localizable.xcstrings").read_text(encoding="utf-8"))["strings"]
    extra = json.loads((HERE / "strings.json").read_text(encoding="utf-8"))
    explicit = set()
    for file in sorted((HERE / "ui").glob("*.js")):
        explicit |= {t for _, t in re.findall(r"\bt\(\s*(['\"])((?:(?!\1)[^\\]|\\.)+)\1", file.read_text(encoding="utf-8"))}
    out, missing = {lang: {} for lang in LANGUAGES}, []

    def leaf(entry, lang):
        local = entry.get("localizations", {}).get(lang, {})
        if "stringUnit" in local:
            return local["stringUnit"]["value"]
        plural = local.get("variations", {}).get("plural", {})
        return {k: v["stringUnit"]["value"] for k, v in plural.items()} or None

    for key in list(dict.fromkeys(used() + list(extra))):
        key = key.replace("\\'", "'")
        for lang in LANGUAGES:
            value = extra.get(key, {}).get(lang) or (leaf(catalog[key], lang) if key in catalog else None)
            if value is None and key in catalog and lang == "en":
                value = key
            if value is None and key in extra and lang == "en":
                value = key
            if value is None:
                if key in explicit or key in extra:
                    missing.append(f"{lang}: {key}")
                continue
            # The Mac app's own wording, with the name this app has.
            def fix(text, lang=lang):
                text = text.replace("Arcane", "Oort NX")
                # A French mark never starts a line.
                return re.sub(r" ([;:!?»])", "\u00a0\\1", text) if lang == "fr" else text
            out[lang][key] = fix(value) if isinstance(value, str) else {k: fix(v) for k, v in value.items()}
    if missing:
        raise SystemExit("Texts missing (add them to desktop/strings.json):\n" + "\n".join(missing))
    return ("// Generated by desktop/scripts/generate.py. Do not edit.\nexport const STRINGS = " + json.dumps(out, ensure_ascii=False, indent=0, sort_keys=True) +
            "\nexport const GAME_WORDS = " + json.dumps(game_words(), ensure_ascii=False, indent=0, sort_keys=True) + "\n")


def game_words():
    """game-words.json, by the plain form ui/words.js looks for."""
    out = {}
    for lang, words in json.loads((HERE / "game-words.json").read_text(encoding="utf-8")).items():
        if lang.startswith("_"):
            continue
        out[lang] = {}
        for word, value in words.items():
            key = re.sub(r"[\s\-_]+", "", word.lower())
            if out[lang].setdefault(key, value) != value:
                raise SystemExit(f"game-words.json: {word!r} has two translations")
    return out


def names():
    icons = dict(re.findall(r'case (\w+) = "\\u\{([0-9A-F]+)\}"', (ROOT / "Sources/NXLibraryCore/Selene/MaterialIcon.swift").read_text(encoding="utf-8")))
    palettes = [[p["id"], p["name"], p["mode"]] for p in json.loads((ROOT / "Resources/Selene/palettes.json").read_text(encoding="utf-8"))]
    return ("// Generated by desktop/scripts/generate.py. Do not edit.\nexport const ICONS = " + json.dumps(icons) +
            "\nexport const PALETTES = " + json.dumps(palettes, ensure_ascii=False) + "\n")


def main():
    stale = []
    for name, text in (("tokens.css", css()), ("strings.js", strings()), ("names.js", names())):
        file = HERE / "ui/gen" / name
        if "--check" in sys.argv:
            if not file.exists() or file.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            file.parent.mkdir(exist_ok=True)
            file.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit(f"Stale: {', '.join(stale)}; run python3 desktop/scripts/generate.py")
    print("ui/gen is up to date." if "--check" in sys.argv else "ui/gen written.")


if __name__ == "__main__":
    main()
